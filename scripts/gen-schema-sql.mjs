// Generates src/lib/schema-sql.ts (CREATE TABLE statements) from prisma/schema.prisma.
// Used to bootstrap a fresh SQLite file at runtime on serverless hosts.
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const sql = execSync("npx prisma migrate diff --from-empty --to-schema-datamodel prisma/schema.prisma --script", { encoding: "utf8" });
const statements = sql
  .split(/;\s*\n/)
  .map((s) => s.replace(/^--.*$/gm, "").trim())
  .filter(Boolean)
  // idempotent so it can also upgrade an existing database
  .map((s) => s.replace(/^CREATE TABLE /, "CREATE TABLE IF NOT EXISTS ").replace(/^CREATE (UNIQUE )?INDEX /, "CREATE $1INDEX IF NOT EXISTS "));
writeFileSync("src/lib/schema-sql.ts", `// AUTO-GENERATED by scripts/gen-schema-sql.mjs – do not edit.\nexport const SCHEMA_SQL: string[] = ${JSON.stringify(statements, null, 2)};\n`);
console.log(`schema-sql: ${statements.length} statements`);
