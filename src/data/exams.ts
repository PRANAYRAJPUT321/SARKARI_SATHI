export const examBySlug = (slug: string) => EXAMS.find((e) => e.slug === slug);
export const EXAM_CATEGORIES = Array.from(new Set(EXAMS.map((e) => e.category)));

export function totalQuestions(e: Exam) {
  return e.sections.reduce((a, s) => a + s.questions, 0);
}
export function totalMarks(e: Exam) {
  return e.sections.reduce((a, s) => a + s.marks, 0);
}

/** cut-off to compare against for a user's category: latest year's value, else GEN */
export function referenceCutoff(e: Exam, category = "GEN"): { value: number; year: number; label?: string } | null {
  const rows = e.cutoff.rows;
  if (!rows.length) return null;
  const latestYear = Math.max(...rows.map((r) => r.year));
  const latest = rows.filter((r) => r.year === latestYear);
  const key = category as keyof typeof latest[number];
  const vals = latest.map((r) => (r[key] as number | undefined) ?? r.GEN).filter((v): v is number => typeof v === "number");
  if (!vals.length) return null;
  // for state/zone-wise rows use the average as a reference
  const value = Math.round((vals.reduce((a, b) => a + b, 0) / vals.length) * 100) / 100;
  return { value, year: latestYear, label: latest.length > 1 ? "avg of listed states/zones" : latest[0].label };
}

